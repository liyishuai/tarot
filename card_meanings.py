# 合并所有牌义
ALL_CARD_MEANINGS = {}
ALL_CARD_MEANINGS.update(MAJOR_ARCANA_MEANINGS)
ALL_CARD_MEANINGS.update(WANDS_MEANINGS)
ALL_CARD_MEANINGS.update(CUPS_MEANINGS)
ALL_CARD_MEANINGS.update(SWORDS_MEANINGS)
ALL_CARD_MEANINGS.update(PENTACLES_MEANINGS)


def get_card_meaning(card_name: str, orientation: str = "upright") -> dict:
    """
    获取指定牌的含义
    
    Args:
        card_name: 牌名
        orientation: 方向，"upright" (正位) 或 "reversed" (逆位)
    
    Returns:
        包含关键词和含义的字典
    """
    card_meanings = ALL_CARD_MEANINGS.get(card_name, {})
    orient = "upright" if orientation == "正位" else "reversed"
    return card_meanings.get(orient, {
        "keywords": "未定义",
        "meaning": "此牌的含义尚未定义"
    })


def format_card_meaning(card_name: str, orientation: str) -> str:
    """
    格式化输出牌的含义
    
    Args:
        card_name: 牌名
        orientation: 方向（正位/逆位）
    
    Returns:
        格式化的牌义字符串
    """
    meaning_data = get_card_meaning(card_name, orientation)
    return f"""
【{card_name} - {orientation}】
关键词：{meaning_data['keywords']}
含义：{meaning_data['meaning']}
"""
